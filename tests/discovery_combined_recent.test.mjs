import assert from 'node:assert/strict';
import fs from 'node:fs';
const source = fs.readFileSync('app/static/main.js', 'utf8');
const start = source.indexOf('        discoveryHubCombinedDateMatches(file, cutoff, now = Date.now()) {');
const end = source.indexOf('        async discoveryHubOpenSelectedAlbums(', start);
const methods = new Function(`return ({${source.slice(start, end)}})`)();
methods.discoveryHubFileKind = () => 'video';
const now = Date.parse('2026-11-10T12:00:00Z');
const cutoff = now - 7 * 86400000;
assert.equal(methods.discoveryHubCombinedDateMatches({type:'video',uploaded_at:'2026-11-09T12:00:00Z'}, cutoff, now), true);
assert.equal(methods.discoveryHubCombinedDateMatches({type:'video',uploaded_at:'2026-10-01T12:00:00Z'}, cutoff, now), false);
assert.equal(methods.discoveryHubCombinedDateMatches({type:'video'}, cutoff, now), false);
assert.equal(methods.discoveryHubCombinedDateMatches({type:'image',uploaded_at:'2026-11-09T12:00:00Z'}, cutoff, now), false);
assert.equal(methods.discoveryHubCombinedDateMatches({type:'video',uploaded_at:'2026-11-11T12:00:00Z'}, cutoff, now), false);
assert.equal(methods.discoveryHubCombinedDateMatches({type:'video',date:'08/11/2026'}, cutoff, now), true);
assert.equal(methods.discoveryHubCombinedDateMatches({type:'video'}, 0, now), true);
const openEnd = source.indexOf('        combinedHistoryDay()', end);
const open = source.slice(end, openEnd);
assert.match(open, /directFiles\.filter\(includeFile\)/);
assert.match(open, /fileUrl && includeFile\(file\)/);
assert.match(open, /for \(const file of ev\.items \|\| \[\]\) if \(includeFile\(file\)\)/);
